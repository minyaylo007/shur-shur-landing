/**
 * Отпечаток сборки: SHA коммита, из которого собран этот фронтенд.
 *
 * Зачем он есть. Смока выката спрашивает боевой домен сразу после
 * `vercel deploy` и должна отличить «край уже отдаёт нашу сборку» от «край ещё
 * отдаёт предыдущую». По возрасту ответа (`age`) это только догадка: кеш края
 * сбрасывается не одномоментно по всем PoP, и переходное состояние с виду
 * неотличимо от поломки — 15.09.2026 на этом трижды покраснел исправный бой.
 * Отпечаток превращает догадку в измеренный факт: на странице либо стоит тот
 * самый коммит, который мы выкатываем, либо чужой.
 *
 * Значение приходит из NEXT_PUBLIC_BUILD_SHA. `NEXT_PUBLIC_*` подставляется на
 * СБОРКЕ, а не в рантайме, поэтому отпечаток переживает предсборку страниц
 * (`dynamicParams = false` + `generateStaticParams` в layout) и одинаково
 * попадает во все четыре локали — тег живёт в общем layout.
 *
 * Переменной нет (dev, CI, превью) — отпечатка на странице просто нет, и
 * ничего не ломается: его спрашивает только смока боевого выката.
 *
 * `||`, а не `??`: переменная, выставленная в пустую строку, тоже должна
 * означать «отпечатка нет».
 */
export const buildSha = (process.env.NEXT_PUBLIC_BUILD_SHA || "").trim();

/**
 * Имя meta-тега с отпечатком. Одна строка на всех: её печатает layout и её же
 * ищет `scripts/smoke-production.sh`. Тег невидим человеку — он в <head>,
 * а не в тексте страницы.
 */
export const BUILD_SHA_META = "x-build-sha";
