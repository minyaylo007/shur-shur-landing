#!/usr/bin/env bash
# Смока БОЕВОГО выката: проверяет домен, который видит человек.
#
#   scripts/smoke-production.sh https://shur-shur.agency <полный SHA выката>
#
# Проверяется: четыре локали ровно по 200, в теле каждой — наш canonical,
# и на каждой стоит отпечаток ИМЕННО ТОЙ сборки, которую мы выкатываем;
# апекс — 308 на /uk без петли редиректов.
#
# --- Почему отпечаток, а не возраст ответа ------------------------------
# Раньше свежесть проверялась порогом `age <= 120`. Порог ловил настоящую
# вещь — переживший выкат ответ, — но выносил приговор по одному замеру в одно
# мгновение. А сброс кеша у края Vercel не одномоментный: 15.09.2026 три выката
# из пяти покраснели на ИСПРАВНОМ бою (прогоны 35004846361, 35010597770,
# 35014441296) — одна локаль в одном PoP ещё отдавала копию предыдущего выката,
# три остальные в ту же секунду были свежие, а через четыре минуты свежими были
# все четыре. Перезапуск той же работы без единой правки проходил зелёным.
#
# Поэтому проверка свежести не убрана, а заменена на более строгую и
# измеримую: страница несёт meta-отпечаток коммита (см. src/lib/build.ts), и
# смока требует совпадения с коммитом выката. «Старое» перестало быть догадкой
# по возрасту и стало фактом: либо на краю наша сборка, либо предыдущая.
# `age` по-прежнему печатается — он диагностика, а не приговор.
#
# --- Почему ожидание, и почему не на всё -------------------------------
# Переходное состояние проходит само, поломка — нет. Поэтому ответ «край ещё
# отдаёт предыдущую сборку» перепрашивается в пределах бюджета, а «ответило не
# 200» и «это не наша страница» валят шаг НЕМЕДЛЕННО: ожиданием это не лечится,
# и жечь на это бюджет нельзя.
#
# Бюджет взят по единственному измерению, которое у нас есть: 15.09 в 19:34
# край отдавал копию предыдущего выката, а через 4 минуты все четыре локали
# были свежими. Берём этот интервал целиком — 240 s. Платится он ТОЛЬКО когда
# край действительно отстал: сошлось с первой попытки — выкат не удлиняется.
set -uo pipefail

base="${1:-}"; base="${base%/}"
want="${2:-}"

# Обе ручки вынесены в переменные окружения, чтобы проверки смоки на подделке
# могли сжать время, не трогая код, который поедет в бой.
BUDGET="${SETTLE_BUDGET_SECONDS:-240}"   # суммарный потолок ОЖИДАНИЯ, секунды
DELAY="${SETTLE_DELAY_SECONDS:-15}"      # пауза между попытками, секунды
META="x-build-sha"                        # имя meta-тега, см. src/lib/build.ts
LOCALES="uk en he ro"

if [ -z "$base" ]; then
  echo "::error::Смоке не передан боевой адрес — проверять нечего"
  exit 1
fi
if [ -z "$want" ]; then
  echo "::error::Смоке не передан SHA выката — сравнивать отпечаток не с чем"
  exit 1
fi

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

declare -A AGE SEEN
REASON=""

# `|| true` обязателен: при set -o pipefail отсутствующий заголовок делает grep
# неуспешным, и без него шаг умирал бы молча — без единой строки о причине.
hdr() { grep -i "^$2:" "$1" | tail -n1 | sed 's/^[^:]*:[ \t]*//' | tr -d '\r' || true; }
short() { printf '%.7s' "${1:-—}"; }

# Один запрос к локали. Печатает строку лога и возвращает:
#   0 — наша страница нашей сборки;
#   1 — переходное состояние: страница наша, но сборка предыдущая (лечится ожиданием);
#   2 — поломка: не 200 или не наша страница (ожиданием НЕ лечится).
probe() {
  local loc="$1" url="$base/$1"
  local head="$tmp/head" body="$tmp/body" code age cache vid sha marker
  code=$(curl -sS -o "$body" -D "$head" -w '%{http_code}' \
         --max-time 30 --retry 2 --retry-delay 5 "$url" || true)
  code="${code:-000}"
  age=$(hdr "$head" age); cache=$(hdr "$head" x-vercel-cache); vid=$(hdr "$head" x-vercel-id)
  case "${age:-0}" in ''|*[!0-9]*) age=0 ;; esac
  # Тег ищем поатрибутно, а не одной строкой: порядок атрибутов в <meta> —
  # дело рендерера, и завязываться на него нельзя.
  sha=$(tr '<' '\n' < "$body" | grep -i "name=\"$META\"" \
        | sed -n 's/.*content="\([^"]*\)".*/\1/p' | head -n1 | tr -cd '0-9a-fA-F')
  AGE[$loc]="$age"; SEEN[$loc]="$sha"
  echo "GET $url -> $code (x-vercel-cache: ${cache:-—}, age: ${age}, x-vercel-id: ${vid:-—}, сборка: $(short "$sha"))"

  if [ "$code" != "200" ]; then
    REASON="$url: ждали 200, получили $code"
    return 2
  fi
  # Маркер нашей страницы: canonical с нашим доменом И этой локалью.
  # Ни заглушка хостинга, ни страница ошибки Vercel такого не отдадут.
  marker="rel=\"canonical\" href=\"$base/$loc\""
  if ! grep -qF "$marker" "$body"; then
    REASON="$url: в теле нет маркера [$marker] — это не наша страница"
    return 2
  fi
  if [ "$sha" != "$want" ]; then
    REASON="$url: на странице сборка ${sha:-«без отпечатка»}, а выкатили $want"
    return 1
  fi
  return 0
}

echo "Боевой адрес: $base"
echo "Выкачен коммит: $want"
echo "Бюджет ожидания края: ${BUDGET}s суммарно, пауза ${DELAY}s между попытками"

started=$(date +%s)
deadline=$((started + BUDGET))
pending="$LOCALES"
round=0
fail=0
note() { echo "  ✗ $*"; fail=1; }

while :; do
  round=$((round + 1))
  next=""; broken=""
  for loc in $pending; do
    probe "$loc"; state=$?
    case "$state" in
      0) [ "$round" -eq 1 ] || echo "  ✓ /$loc: сошёлся с попытки $round, ждали $(( $(date +%s) - started ))s" ;;
      1) next="$next $loc"; echo "  … $REASON" ;;
      *) broken="$broken $loc"; echo "  ✗ $REASON" ;;
    esac
  done

  # Поломка валит шаг немедленно, не потратив ни секунды бюджета.
  if [ -n "$broken" ]; then
    echo "::error::Смока не прошла: ${broken# } — ожиданием это не лечится (не 200 либо не наша страница), ждать не стали"
    exit 1
  fi
  [ -n "$next" ] || break

  now=$(date +%s)
  if [ $((now + DELAY)) -gt "$deadline" ]; then
    for loc in $next; do
      note "$base/$loc: край всё ещё отдаёт сборку ${SEEN[$loc]:-«без отпечатка»} (age ${AGE[$loc]}s); ждали $((now - started))s, попыток $round"
    done
    echo "::error::Смока не прошла: за $((now - started))s ожидания и ${round} попыток край так и не перешёл на выкаченную сборку $want (бюджет ${BUDGET}s)"
    exit 1
  fi
  echo "  … ждём ${DELAY}s и спрашиваем снова:${next} (потрачено $((now - started))s из ${BUDGET}s)"
  sleep "$DELAY"
  pending="$next"
done

waited=$(( $(date +%s) - started ))
echo "Все локали отдают выкаченную сборку: попыток $round, ожидание ${waited}s"

# Апекс: 308 на /uk и не больше двух переходов до 200.
# Петля редиректов на домене — самая дорогая поломка: сайта нет, а все четыре
# локали по отдельности при этом живые.
apex_code=$(curl -sS -o /dev/null -w '%{http_code}' --max-time 30 "$base/" || true)
apex_to=$(curl -sS -o /dev/null -w '%{redirect_url}' --max-time 30 "$base/" || true)
echo "GET $base/ -> ${apex_code:-000} -> ${apex_to:-—}"
[ "${apex_code:-000}" = "308" ] || note "$base/: ждали 308, получили ${apex_code:-000}"
[ "$apex_to" = "$base/uk" ] || note "$base/: ждали переход на $base/uk, получили '${apex_to:-—}'"

chain=$(curl -sS -L -o /dev/null --max-redirs 5 \
        -w '%{num_redirects} %{http_code} %{url_effective}' --max-time 30 "$base/" || true)
set -- ${chain:-9 000 —}
echo "Цепочка апекса: переходов=$1, итог=$2 ($3)"
[ "$1" -le 2 ] || note "$base/: $1 переходов до конца — похоже на петлю редиректов"
[ "$2" = "200" ] || note "$base/: цепочка закончилась кодом $2, а не 200"
[ "$3" = "$base/uk" ] || note "$base/: цепочка привела на '$3', а не на $base/uk"

if [ "$fail" -ne 0 ]; then
  echo "::error::Смока не прошла: боевой сайт отдаёт не то, что мы выкатили (подробности выше)"
  exit 1
fi
echo "Смока прошла: $base — 4 локали по 200 с нашим canonical и сборкой $want, апекс 308 на /uk"
